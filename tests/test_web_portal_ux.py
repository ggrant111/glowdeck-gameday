#!/usr/bin/env python3
"""Phase 7D portal UX contracts.

Protects the six-task information architecture and verifies that the
declarative DOM relocation retains every existing control/API binding.
The embedded JavaScript syntax is separately checked by check_web_ui.py.
"""
from pathlib import Path
import re
from collections import Counter
s=Path("include/WebUi.h").read_text(encoding="utf-8")
assert "<script>" in s and "</script>" in s and "<style>" in s
html=s.split("<script>",1)[0]
js=s.split("<script>",1)[1].split("</script>",1)[0]
ids=re.findall(r'\bid="([^"]+)"',html)
duplicates=[key for key,value in Counter(ids).items() if value!=1]
assert not duplicates, f"Duplicate HTML ID(s): {duplicates}"
ids=set(ids)
expected_nav=("dashboard","games","customize","lab","device","events")
nav=re.search(r'<nav class="tabs" aria-label="GameDay navigation">(.*?)</nav>',
              html,re.S)
assert nav
nav_ids=re.findall(r'class="tab(?: selected)?" data-tab="([^"]+)"',
                   nav.group(1))
assert tuple(nav_ids)==expected_nav,(nav_ids,expected_nav)
for page in expected_nav:
    assert page in ids,page
    assert f'{{page:"{page}"}}' in js,page
for old,new in {
    "display":"customize",
    "devices":"customize",
    "rear":"customize",
    "settings":"device",
    "firmware":"device"
}.items():
    assert re.search(rf'\b{old}:\s*{{page:"{new}"',js),(old,new)

zones={
 "customize":("zone-favorites","zone-screen","zone-wled",
              "zone-audio","zone-hardware"),
 "lab":("lab-screen","lab-audio","lab-wled",
        "lab-hardware","lab-full"),
 "device":("zone-network","zone-maintenance","zone-connection")
}
for page,names in zones.items():
    panel=html.split(f'<section id="{page}" class="panel"',1)[1].split(
        "</section>",1)[0]
    for name in names:
        assert name in ids,(page,name)
        assert f'id="{name}"' in panel,(page,name)
        assert f'data-jump="{name}"' in panel,(page,name)
        assert 'document.querySelectorAll("[data-jump]")' in js
for key in ("mount-favorites","mount-screen","mount-wled",
            "mount-audio","mount-hardware","mount-lab-screen",
            "mount-lab-audio","mount-lab-wled","mount-lab-hardware",
            "mount-lab-case","mount-lab-full","mount-network",
            "mount-maintenance","mount-connection"):
    assert key in ids,key

# Every literal DOM id referenced in JavaScript must actually exist in the
# static markup. Dynamic WLED IDs are generated by renderDevices().
for control in re.findall(r'\$\("([^"]+)"\)',js):
    assert control in ids,f"Missing target referenced by JavaScript: {control}"

# All source nodes of declarative mounts are present and unique.
mount_block=js.split("function mountPortalModules(){",1)[1].split(
    "const PORTAL_ROUTES",1)[0]
mount_targets=re.findall(r'\b(?:place|moveCard)\("([^"]+)"\s*,\s*"([^"]+)"',mount_block)
source_ids=[source for source,_ in mount_targets]
assert len(source_ids)==len(set(source_ids)),source_ids
for source,target in mount_targets:
    assert source in ids,(source,"missing source")
    assert target in ids,(target,"missing destination")

for source,target in (
    ("favoriteTeamGrid","mount-favorites"),
    ("rearFollowedList","mount-favorites"),
    ("cycleGames","mount-screen"),
    ("overlayEnabled","mount-screen"),
    ("wledScan","mount-wled"),
    ("deviceList","mount-wled"),
    ("wledGoalStyle","mount-wled"),
    ("s3AudioCard","mount-audio"),
    ("s3CaseLedCard","mount-hardware"),
    ("rearEnabled","mount-hardware"),
    ("apName","mount-connection"),
    ("deviceIp","mount-connection"),
    ("bin","mount-maintenance"),
    ("ssid","mount-network"),
    ("wledTestGoalHome","mount-lab-wled"),
    ("rearTestHome","mount-lab-hardware"),
    ("rearDiagRed","mount-lab-hardware"),
    ("rearFullHome","mount-lab-full")
):
    assert (source,target) in mount_targets,(source,target)

# Regression: Phase 7D accidentally left discovery in the invisible legacy
# devices panel. Ensure the original scan *and* manual-IP controls are in
# the card moved into the visible WLED Customize destination.
discovery=html.split('id="wledScan"',1)[0].rsplit('<div class="card"',1)[-1]
assert 'Find &amp; add WLED devices' in discovery
assert 'id="wledManualIp"' in html
assert 'id="wledManualCheck"' in html
assert 'id="wledDiscovered"' in html
assert 'id="wledScanStatus"' in html
assert mount_block.index('moveCard("wledScan","mount-wled")') < mount_block.index(
    'moveCard("deviceList","mount-wled")')
assert '$("wledScan").onclick=' in js
assert '"/api/wled/discover"' in js
assert '"/api/wled/discovery"' in js
assert '"/api/wled/probe"' in js

# Actual test buttons are reparented, NOT duplicated or issued on boot.
for test,target in (
    ('$("overlayTestGoal").closest(".actions")',"mount-lab-screen"),
    ('$("goalGifPreview")',"mount-lab-screen"),
    ('$("testHome").closest(".actions")',"mount-lab-wled"),
    ('$("s3AudioPreview").closest(".actions")',"mount-lab-audio"),
    ('$("s3AudioDiagnostics")',"mount-lab-audio"),
    ('document.querySelector(".s3-case-test").closest(".actions")',"mount-lab-case"),
):
    assert test in mount_block,(test,target)
    assert f'$("'+target+'")' in mount_block or f'"{target}"' in mount_block,target

# Don't turn S3-only tests into invalid CYD actions.
assert '$("lab-audio").hidden=!s3;' in js
assert '$("mount-lab-hardware").hidden=s3;' in js
assert '$("mount-lab-case").hidden=!s3;' in js
assert 'data-jump="lab-audio"' in html
assert 'if(audioTab)audioTab.hidden=!s3;' in js
assert 'document.querySelectorAll(".s3-case-test")' in js

# Safeguard consistent shared-save behavior; special 7B and 7C controls
# keep their separate Apply and Save endpoints and user-facing explanation.
assert 'id="portalSave"' in html and 'id="deviceSave"' in html
assert '$("portalSave").onclick=()=>perform(saveConfig);' in js
assert '$("deviceSave").onclick=()=>perform(saveConfig);' in js
assert "setPortalDirty(false);" in js
assert 'trackPortalChanges();' in js
assert 'mountPortalModules();' in js
assert 'await loadConfig();' in js
assert js.index('mountPortalModules();')<js.index('await loadConfig();')
assert "s3AudioVolumeApply" in ids and "s3CaseSave" in ids
assert "saveFavorites" in ids and "s3SoundUploadForm" in ids
assert "Save all settings" not in html
assert "no CDN" in s.lower() or "no CDN" in s

# Arena HUD is a render-only live view of actual NHL game data, not a new
# second trigger path; preserve the existing favorite and follow APIs.
for name in ("heroAwayMark","heroHomeMark","heroScore","heroStatus",
             "heroArmStatus","heroLiveTag","heroGameMode","platformTag"):
    assert name in ids,name
assert "function renderBroadcastHero(){" in js
assert "renderBroadcastHero();" in js
assert 'const armed=currentGames.find(g=>g.id===s.selectedId);' in js
assert '/api/rear/follow' in js and '/api/display/favorites' in js
assert 'function saveConfig(){' in js
assert 'function deviceSettings(){' in js

print("PASS Phase 7D web portal: unique IDs, 6 routes, grouped test lab, "
      "S3/CYD isolation, retained APIs, shared Save and arena scoreboard")
